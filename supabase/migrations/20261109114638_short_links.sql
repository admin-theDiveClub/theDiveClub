-- Short links: thediveclub.org/<code> (UV, 9 Nov; docs/design/short-links.md).
--
--   T-BC26      a tournament            the TD chooses BC26
--   T-BC26-7    match 7 of it           automatic
--   L-BCDAM     a league                the LD chooses BCDAM
--   L-BCDAM-14  match 14 of it          automatic
--   4821        a social match          automatic
--
-- The stored code is only the part somebody chose. The letter and the dashes
-- are added when it is shown, so no address on the site can ever clash with one.
--
-- Nothing that creates a match is changed. A league or tournament match is only
-- tied to its competition by the fixture's match_id, a moment after the match
-- is made, so the number lives on the fixture and is given out by a trigger when
-- that link is written. A rematch on the same fixture keeps its number.
--
-- A short link grants nothing. tdc_resolve_short_code is the only thing a
-- stranger can call, and it can only answer with an address built here from an
-- id, so a code can never lead off the site. The page still checks who you are.

-- ─────────────────────────────────────────────────────────────────
-- The columns
-- ─────────────────────────────────────────────────────────────────

alter table public.tbl_tournaments
	add column short_code        text,
	add column short_code_by     uuid references auth.users (id) on delete set null,
	add column next_match_number integer not null default 1;

alter table public.tbl_leagues
	add column short_code        text,
	add column short_code_by     uuid references auth.users (id) on delete set null,
	add column next_match_number integer not null default 1;

alter table public.tbl_tournament_fixtures
	add column match_number integer check (match_number is null or match_number > 0);

alter table public.tbl_league_fixtures
	add column match_number integer check (match_number is null or match_number > 0);

-- A number for every match, from 1000 so a code is never one digit. Only a
-- social match shows it: one in a league or tournament shows that code instead.
alter table public.tbl_matches
	add column short_number bigint generated by default as identity (start with 1000);

create unique index tbl_matches_short_number_key on public.tbl_matches (short_number);

comment on column public.tbl_tournaments.short_code is
	'The part of the short link the TD chose, without the T-. Written only by tdc_set_short_code. docs/design/short-links.md.';
comment on column public.tbl_tournaments.short_code_by is
	'The only account that may change short_code. Starts as whoever created the tournament.';
comment on column public.tbl_leagues.short_code is
	'The part of the short link the LD chose, without the L-. Written only by tdc_set_short_code. docs/design/short-links.md.';
comment on column public.tbl_leagues.short_code_by is
	'The only account that may change short_code. Starts as whoever created the league.';
comment on column public.tbl_tournament_fixtures.match_number is
	'The number at the end of this match''s short link. Given when the fixture first gets a match, never reused.';
comment on column public.tbl_league_fixtures.match_number is
	'The number at the end of this match''s short link. Counted across the league''s seasons, never reused.';
comment on column public.tbl_matches.short_number is
	'A social match''s short link. Never changes.';


-- ─────────────────────────────────────────────────────────────────
-- A suggested code
--
-- No vowels, so it cannot spell a word, and none of the look-alikes 0, O, 1, I
-- and L. 28 characters, five of them: about 17 million.
-- ─────────────────────────────────────────────────────────────────

create function private.tdc_new_short_code(p_kind text)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
	c_letters constant text := 'BCDFGHJKMNPQRSTVWXYZ23456789';
	v_code text;
	v_taken boolean;
begin
	loop
		select string_agg(substr(c_letters, 1 + floor(random() * length(c_letters))::int, 1), '')
			into v_code
			from generate_series(1, 5);

		if p_kind = 'tournament' then
			select exists (select 1 from public.tbl_tournaments where short_code = v_code) into v_taken;
		else
			select exists (select 1 from public.tbl_leagues where short_code = v_code) into v_taken;
		end if;

		exit when not v_taken;
	end loop;
	return v_code;
end;
$$;

revoke execute on function private.tdc_new_short_code(text) from public, anon, authenticated;

-- Everything already there gets one too, then the column can be required.
do $$
declare
	r record;
begin
	for r in select id from public.tbl_tournaments loop
		update public.tbl_tournaments
			set short_code = private.tdc_new_short_code('tournament'), short_code_by = created_by
			where id = r.id;
	end loop;

	for r in select id from public.tbl_leagues loop
		update public.tbl_leagues
			set short_code = private.tdc_new_short_code('league'), short_code_by = created_by
			where id = r.id;
	end loop;
end;
$$;

-- Numbers for the matches already played, in the order they were made.
update public.tbl_tournament_fixtures f
set match_number = n.num
from (
	select f2.id, row_number() over (partition by f2.tournament_id order by m.created_at, f2.id) as num
	from public.tbl_tournament_fixtures f2
	join public.tbl_matches m on m.id = f2.match_id
) n
where f.id = n.id;

update public.tbl_league_fixtures f
set match_number = n.num
from (
	select f2.id, row_number() over (partition by s.league_id order by m.created_at, f2.id) as num
	from public.tbl_league_fixtures f2
	join public.tbl_league_seasons s on s.id = f2.league_season_id
	join public.tbl_matches m on m.id = f2.match_id
) n
where f.id = n.id;

update public.tbl_tournaments t
set next_match_number = 1 + coalesce((
	select max(f.match_number) from public.tbl_tournament_fixtures f where f.tournament_id = t.id
), 0);

update public.tbl_leagues l
set next_match_number = 1 + coalesce((
	select max(f.match_number)
	from public.tbl_league_fixtures f
	join public.tbl_league_seasons s on s.id = f.league_season_id
	where s.league_id = l.id
), 0);

alter table public.tbl_tournaments
	alter column short_code set not null,
	add constraint tbl_tournaments_short_code_shape check (short_code ~ '^[A-Z0-9]{2,8}$');

alter table public.tbl_leagues
	alter column short_code set not null,
	add constraint tbl_leagues_short_code_shape check (short_code ~ '^[A-Z0-9]{2,8}$');

-- One table each, so T-BC26 and L-BC26 can both exist.
create unique index tbl_tournaments_short_code_key on public.tbl_tournaments (short_code);
create unique index tbl_leagues_short_code_key on public.tbl_leagues (short_code);

create unique index tbl_tournament_fixtures_match_number_key
	on public.tbl_tournament_fixtures (tournament_id, match_number)
	where match_number is not null;


