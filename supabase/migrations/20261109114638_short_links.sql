create function private.tdc_short_code_on_create()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
	new.short_code := coalesce(new.short_code, private.tdc_new_short_code(tg_argv[0]));
	new.short_code_by := coalesce(new.short_code_by, new.created_by);
	return new;
end;
$$;

revoke execute on function private.tdc_short_code_on_create() from public, anon, authenticated;

create trigger tbl_tournaments_short_code
	before insert on public.tbl_tournaments
	for each row execute function private.tdc_short_code_on_create('tournament');

create trigger tbl_leagues_short_code
	before insert on public.tbl_leagues
	for each row execute function private.tdc_short_code_on_create('league');

-- Taking the next number by updating the competition's row holds its lock, so
-- two matches started together cannot get the same one.
create function private.tdc_tournament_fixture_number()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
	if new.match_id is not null and new.match_number is null then
		update public.tbl_tournaments
			set next_match_number = next_match_number + 1
			where id = new.tournament_id
			returning next_match_number - 1 into new.match_number;
	end if;
	return new;
end;
$$;

revoke execute on function private.tdc_tournament_fixture_number() from public, anon, authenticated;

create trigger tbl_tournament_fixtures_number
	before insert or update of match_id on public.tbl_tournament_fixtures
	for each row execute function private.tdc_tournament_fixture_number();

create function private.tdc_league_fixture_number()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
	if new.match_id is not null and new.match_number is null then
		update public.tbl_leagues l
			set next_match_number = l.next_match_number + 1
			from public.tbl_league_seasons s
			where s.id = new.league_season_id and l.id = s.league_id
			returning l.next_match_number - 1 into new.match_number;
	end if;
	return new;
end;
$$;

revoke execute on function private.tdc_league_fixture_number() from public, anon, authenticated;

create trigger tbl_league_fixtures_number
	before insert or update of match_id on public.tbl_league_fixtures
	for each row execute function private.tdc_league_fixture_number();


-- ─────────────────────────────────────────────────────────────────
-- Checking a code a director has typed
-- ─────────────────────────────────────────────────────────────────

-- A page holds a league's season, not the league, so both are accepted.
create function private.tdc_short_target(p_kind text, p_id uuid, out kind text, out id uuid)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
	if p_kind = 'tournament' then
		select 'tournament', t.id into kind, id from public.tbl_tournaments t where t.id = p_id;
	elsif p_kind = 'league' then
		select 'league', l.id into kind, id from public.tbl_leagues l where l.id = p_id;
	elsif p_kind = 'season' then
		select 'league', s.league_id into kind, id from public.tbl_league_seasons s where s.id = p_id;
	else
		raise exception 'TDC (Error): that is not something a short code belongs to.';
	end if;

	if id is null then
		raise exception 'TDC (Error): that % could not be found.', p_kind;
	end if;
end;
$$;

revoke execute on function private.tdc_short_target(text, uuid) from public, anon, authenticated;

-- Null means nothing is wrong with it. The worst words only: a whole-word list
-- for those that hide inside ordinary words.
create function private.tdc_short_code_problem(p_kind text, p_id uuid, p_code text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
	v_taken boolean;
begin
	if p_code !~ '^[A-Z0-9]*$' then return 'invalid'; end if;
	if length(p_code) < 2 then return 'too_short'; end if;
	if length(p_code) > 8 then return 'too_long'; end if;

	if p_code ~ '(FUCK|SHIT|CUNT|NIGG|KAFFIR|FAGGOT|WANKER|BITCH|PORN)'
		or p_code in ('ASS', 'ARSE', 'DICK', 'COCK', 'TWAT', 'PISS', 'RAPE', 'SEX',
			'NAZI', 'HITLER', 'WHORE', 'SLUT', 'FAG', 'PUSSY')
	then
		return 'blocked';
	end if;

	if p_kind = 'tournament' then
		select exists (select 1 from public.tbl_tournaments t where t.short_code = p_code and t.id <> p_id) into v_taken;
	else
		select exists (select 1 from public.tbl_leagues l where l.short_code = p_code and l.id <> p_id) into v_taken;
	end if;

	if v_taken then return 'taken'; end if;
	return null;
end;
$$;

revoke execute on function private.tdc_short_code_problem(text, uuid, text) from public, anon, authenticated;

-- The field's live feedback: available, yours, too_short, too_long, invalid,
-- blocked or taken.
create function public.tdc_short_code_status(p_kind text, p_id uuid, p_code text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
	v_target record;
	v_code text := upper(btrim(coalesce(p_code, '')));
	v_mine text;
	v_problem text;
begin
	select * into v_target from private.tdc_short_target(p_kind, p_id);

	v_problem := private.tdc_short_code_problem(v_target.kind, v_target.id, v_code);
	if v_problem is not null then return v_problem; end if;

	if v_target.kind = 'tournament' then
		select t.short_code into v_mine from public.tbl_tournaments t where t.id = v_target.id;
	else
		select l.short_code into v_mine from public.tbl_leagues l where l.id = v_target.id;
	end if;

	return case when v_mine = v_code then 'yours' else 'available' end;
end;
$$;

revoke execute on function public.tdc_short_code_status(text, uuid, text) from public, anon;
grant execute on function public.tdc_short_code_status(text, uuid, text) to authenticated;


-- ─────────────────────────────────────────────────────────────────
-- Changing one
--
-- Only whoever set it (UV, 9 Nov), and only while they still run it. The old
-- code is released at once: nothing remembers it.
-- ─────────────────────────────────────────────────────────────────

create function public.tdc_set_short_code(p_kind text, p_id uuid, p_code text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
	v_uid uuid := (select auth.uid());
	v_target record;
	v_code text := upper(btrim(coalesce(p_code, '')));
	v_by uuid;
	v_runs boolean;
	v_problem text;
begin
	if v_uid is null then
		raise exception 'Sign in to change a short link.';
	end if;

	select * into v_target from private.tdc_short_target(p_kind, p_id);

	if v_target.kind = 'tournament' then
		select t.short_code_by into v_by from public.tbl_tournaments t where t.id = v_target.id for update;
		v_runs := private.tdc_can_run_tournament(v_target.id);
	else
		select l.short_code_by into v_by from public.tbl_leagues l where l.id = v_target.id for update;
		v_runs := private.tdc_can_manage_league(v_target.id);
	end if;

	if v_by is distinct from v_uid or not coalesce(v_runs, false) then
		raise exception 'Only the person who set this short link may change it.';
	end if;

	v_problem := private.tdc_short_code_problem(v_target.kind, v_target.id, v_code);
	if v_problem = 'taken' then raise exception 'That code is taken. Try another.'; end if;
	if v_problem = 'too_short' then raise exception 'A code needs at least 2 characters.'; end if;
	if v_problem = 'too_long' then raise exception 'A code can have at most 8 characters.'; end if;
	if v_problem = 'blocked' then raise exception 'That code is not allowed. Try another.'; end if;
	if v_problem is not null then raise exception 'A code can only have letters and numbers.'; end if;

	begin
		if v_target.kind = 'tournament' then
			update public.tbl_tournaments set short_code = v_code where id = v_target.id;
		else
			update public.tbl_leagues set short_code = v_code where id = v_target.id;
		end if;
	exception when unique_violation then
		raise exception 'That code is taken. Try another.';
	end;

	return v_code;
end;
$$;

revoke execute on function public.tdc_set_short_code(text, uuid, text) from public, anon;
grant execute on function public.tdc_set_short_code(text, uuid, text) to authenticated;


-- ─────────────────────────────────────────────────────────────────
-- What a page shows: its code, and whether this person may change it
-- ─────────────────────────────────────────────────────────────────

create function public.tdc_short_link(p_kind text, p_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
	v_uid uuid := (select auth.uid());
	v_target record;
	v_code text;
	v_by uuid;
	v_runs boolean := false;
	v_number bigint;
	v_set_by text;
begin
	if p_kind = 'match' then
		select 'T-' || t.short_code || '-' || f.match_number into v_code
			from public.tbl_tournament_fixtures f
			join public.tbl_tournaments t on t.id = f.tournament_id
			where f.match_id = p_id
			limit 1;

		if v_code is null then
			select 'L-' || l.short_code || '-' || f.match_number into v_code
				from public.tbl_league_fixtures f
				join public.tbl_league_seasons s on s.id = f.league_season_id
				join public.tbl_leagues l on l.id = s.league_id
				where f.match_id = p_id
				limit 1;
		end if;

		if v_code is null then
			select m.short_number into v_number from public.tbl_matches m where m.id = p_id;
			if v_number is null then
				raise exception 'TDC (Error): that match could not be found.';
			end if;
			v_code := v_number::text;
		end if;

		return jsonb_build_object('code', v_code, 'can_change', false, 'set_by', null);
	end if;

	select * into v_target from private.tdc_short_target(p_kind, p_id);

	if v_target.kind = 'tournament' then
		select 'T-' || t.short_code, t.short_code_by into v_code, v_by
			from public.tbl_tournaments t where t.id = v_target.id;
		if v_uid is not null then v_runs := private.tdc_can_run_tournament(v_target.id); end if;
	else
		select 'L-' || l.short_code, l.short_code_by into v_code, v_by
			from public.tbl_leagues l where l.id = v_target.id;
		if v_uid is not null then v_runs := private.tdc_can_manage_league(v_target.id); end if;
	end if;

	-- The name is for the people running it, who are told who can change it.
	-- A stranger on a poster has no need of it.
	if coalesce(v_runs, false) then
		select p.display_name into v_set_by from public.tbl_players p where p.user_id = v_by;
	end if;

	return jsonb_build_object(
		'code', v_code,
		'can_change', v_uid is not null and v_by = v_uid and coalesce(v_runs, false),
		'set_by', v_set_by
	);
end;
$$;

revoke execute on function public.tdc_short_link(text, uuid) from public;
grant execute on function public.tdc_short_link(text, uuid) to anon, authenticated;


-- ─────────────────────────────────────────────────────────────────
-- Following a link
--
-- Answers { path } or { reason }. A reason never names the tournament or
-- league, so a mistyped code tells a stranger nothing.
-- ─────────────────────────────────────────────────────────────────

create function public.tdc_resolve_short_code(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
	v_code text := upper(btrim(coalesce(p_code, '')));
	v_uid uuid := (select auth.uid());
	v_me uuid;
	v_parts text[];
	v_kind text;
	v_id uuid;
	v_season uuid;
	v_match uuid;
	v_shared boolean;
	v_part_of boolean := false;
begin
	if length(v_code) > 24 then
		return jsonb_build_object('reason', 'invalid');
	end if;

	if v_uid is not null then
		v_me := private.tdc_me();
	end if;

	-- A social match: digits and nothing else.
	if v_code ~ '^[0-9]{1,15}$' then
		select m.id into v_match
			from public.tbl_matches m
			where m.short_number = v_code::bigint
				and not exists (select 1 from public.tbl_tournament_fixtures f where f.match_id = m.id)
				and not exists (select 1 from public.tbl_league_fixtures f where f.match_id = m.id);

		if v_match is null then
			return jsonb_build_object('reason', 'not_found');
		end if;
		return jsonb_build_object('path', '/match/?id=' || v_match);
	end if;

	v_parts := regexp_match(v_code, '^([TL])-([A-Z0-9]{2,8})(?:-([0-9]{1,9}))?$');
	if v_parts is null then
		return jsonb_build_object('reason', 'invalid');
	end if;

	v_kind := v_parts[1];

	if v_kind = 'T' then
		select t.id into v_id from public.tbl_tournaments t where t.short_code = v_parts[2];
	else
		select l.id into v_id from public.tbl_leagues l where l.short_code = v_parts[2];
	end if;

	if v_id is null then
		return jsonb_build_object('reason', 'not_found');
	end if;

	-- A match inside it.
	if v_parts[3] is not null then
		if v_kind = 'T' then
			select f.match_id into v_match
				from public.tbl_tournament_fixtures f
				where f.tournament_id = v_id and f.match_number = v_parts[3]::int;
			if v_match is null then
				return jsonb_build_object('reason', 'no_such_match');
			end if;
			return jsonb_build_object('path', '/match/?id=' || v_match);
		end if;

		select f.match_id into v_match
			from public.tbl_league_fixtures f
			join public.tbl_league_seasons s on s.id = f.league_season_id
			where s.league_id = v_id and f.match_number = v_parts[3]::int
			limit 1;
		if v_match is null then
			return jsonb_build_object('reason', 'no_such_match');
		end if;
		return jsonb_build_object('path', '/leagues/card/?m=' || v_match);
	end if;

	if v_kind = 'T' then
		if v_uid is not null then
			v_part_of := private.tdc_can_run_tournament(v_id)
				or private.tdc_competition_rank(v_id) > 0
				or exists (
					select 1 from public.tbl_tournament_entrants e
					where e.tournament_id = v_id and e.player_id = v_me and e.status <> 'withdrawn'
				);
		end if;

		if coalesce(v_part_of, false) then
			return jsonb_build_object('path', '/tournaments/bracket/?t=' || v_id);
		end if;

		select p.is_public into v_shared from public.tbl_tournament_posters p where p.tournament_id = v_id;
		if not coalesce(v_shared, false) then
			return jsonb_build_object('reason', 'poster_not_shared');
		end if;
		return jsonb_build_object('path', '/tournaments/poster/?t=' || v_id);
	end if;

	-- A league opens its newest season.
	select s.id into v_season
		from public.tbl_league_seasons s
		where s.league_id = v_id
		order by s.created_at desc, s.id
		limit 1;

	if v_season is null then
		return jsonb_build_object('reason', 'no_season');
	end if;

	if v_uid is not null then
		v_part_of := private.tdc_can_manage_league(v_id)
			or private.tdc_league_season_rank(v_season) > 0
			or exists (
				select 1 from public.tbl_league_season_entrants e
				where e.league_season_id = v_season and e.player_id = v_me and e.status <> 'withdrawn'
			);
	end if;

	if coalesce(v_part_of, false) then
		return jsonb_build_object('path', '/leagues/season/?s=' || v_season);
	end if;
	return jsonb_build_object('path', '/leagues/join/?s=' || v_season);
end;
$$;

revoke execute on function public.tdc_resolve_short_code(text) from public;
grant execute on function public.tdc_resolve_short_code(text) to anon, authenticated;
